-- Row and column of the first line of `files` matching `pattern` (the
-- capture is the name), inside the block that starts at `within` if given.
local function find_go(files, within, pattern)
    for _, path in ipairs(files) do
        local lines = file_lines(path) or {}
        local inside = within == nil
        for row, line in ipairs(lines) do
            if within and line:match(within) then
                inside = true
            elseif within and inside and line:match("^}") then
                inside = false
            elseif inside then
                local name_col = line:match(pattern)
                if name_col then
                    return { path = path, row = row - 1, col = name_col - 1 }
                end
            end
        end
    end
    return nil
end

local function escape(name)
    return (name:gsub("%p", "%%%0"))
end

-- Where a .proto declaration is in the generated Go code.
function M.go_place(files, target)
    if target.kind == "rpc" then
        return find_go(files, "^type " .. escape(target.service or "") .. "Server interface {", "^\t()" .. escape(target.name) .. "%(")
    elseif target.kind == "service" then
        return find_go(files, nil, "^type ()" .. escape(target.name) .. "Server interface")
    elseif target.kind == "message" or target.kind == "enum" then
        return find_go(files, nil, "^type ()" .. escape((target.path:gsub("%.", "_"))) .. " ")
    elseif target.kind == "field" then
        local struct = escape((target.path:gsub("%.", "_")))
        return find_go(files, "^type " .. struct .. " struct {", "^\t()" .. escape(M.go_name(target.name)) .. "%s")
            or find_go(files, nil, "^type ()" .. struct .. " struct")
    end
end

-- What a position in a generated Go file means for the .proto:
-- { kind = rpc|service|message|field|enum, service, name, path }.
function M.go_target(lines, row, col)
    local text = table.concat(lines, "\n")
    local ok, parser = pcall(vim.treesitter.get_string_parser, text, "go")
    if not ok then
        return nil
    end
    local node = parser:parse()[1]:root():named_descendant_for_range(row, col, row, col)
    local function name_of(n)
        local name = n and n:field("name")[1]
        return name and vim.treesitter.get_node_text(name, text)
    end
    local function service_of(type_name)
        local service = type_name and (type_name:match("^Unimplemented(.+)Server$")
            or type_name:match("^Unsafe(.+)Server$") or type_name:match("^(.+)Server$")
            or type_name:match("^(.+)Client$"))
        return service and (service:gsub("^%l", string.upper))
    end
    -- The generated service types: the interfaces, Unimplemented…Server
    -- and the unexported client.
    local function service_type(type_name, is_interface)
        return (is_interface or type_name:match("^Unimplemented.+Server$") or type_name:match("^%l.*Client$"))
            and service_of(type_name)
    end
    -- Msg of (x *Msg), (Msg), (x *Msg[T]).
    local function receiver_type(method)
        local params = method:field("receiver")[1]
        local declaration = params and params:named_child(0)
        local type_node = declaration and declaration:field("type")[1]
        while type_node and type_node:type() ~= "type_identifier" do
            if type_node:type() == "pointer_type" then
                type_node = type_node:named_child(0)
            elseif type_node:type() == "generic_type" then
                type_node = type_node:field("type")[1]
            else
                type_node = nil
            end
        end
        return type_node and vim.treesitter.get_node_text(type_node, text)
    end
    while node do
        local kind = node:type()
        if kind == "method_elem" or kind == "method_spec" then
            local owner = node:parent()
            while owner and owner:type() ~= "type_spec" do
                owner = owner:parent()
            end
            local service = owner and service_of(name_of(owner))
            if service then
                return { kind = "rpc", service = service, name = name_of(node) }
            end
            return nil
        elseif kind == "method_declaration" then
            local type_name = receiver_type(node)
            local name = name_of(node)
            local service = type_name and service_type(type_name, false)
            if service then
                return { kind = "rpc", service = service, name = name }
            end
            if type_name and name:match("^Get.") then
                return { kind = "field", path = type_name, name = name:sub(4) }
            end
            return type_name and { kind = "message", path = type_name } or nil
        elseif kind == "field_declaration" then
            local owner = node:parent()
            while owner and owner:type() ~= "type_spec" do
                owner = owner:parent()
            end
            return owner and { kind = "field", path = name_of(owner), name = name_of(node) } or nil
        elseif kind == "type_spec" then
            local type_node = node:field("type")[1]
            local name = name_of(node)
            local service = service_type(name, type_node and type_node:type() == "interface_type")
            if service then
                return { kind = "service", name = service }
            end
            local is_struct = type_node and type_node:type() == "struct_type"
            return { kind = is_struct and "message" or "enum", path = name }
        elseif kind == "const_spec" then
            local type_node = node:field("type")[1]
            return type_node and { kind = "enum", path = vim.treesitter.get_node_text(type_node, text) } or nil
        end
        node = node:parent()
    end
    return nil
end

-- The .proto declaration for a Go target.
function M.proto_place(lines, target)
    local declarations = M.proto_declarations(lines)
    local function find(test)
        for _, declaration in ipairs(declarations) do
            if test(declaration) then
                return declaration
            end
        end
    end
    -- Outer_Inner is Outer.Inner, or a name with "_" in it.
    local function same_path(declaration, go_path)
        return declaration.path == go_path:gsub("_", ".") or declaration.path:gsub("%.", "_") == go_path
    end
    if target.kind == "rpc" then
        return find(function(d)
            return d.kind == "rpc" and d.name == target.name and d.service == target.service
        end) or find(function(d)
            return d.kind == "rpc" and d.name == target.name
        end)
    elseif target.kind == "service" then
        return find(function(d)
            return d.kind == "service" and d.name == target.name
        end)
    elseif target.kind == "field" then
        return find(function(d)
            return d.kind == "field" and same_path(d, target.path) and M.go_name(d.name) == target.name
        end) or find(function(d)
            return d.kind == "message" and same_path(d, target.path)
        end)
    end
    return find(function(d)
        return d.kind == target.kind and same_path(d, target.path)
    end) or find(function(d)
        return (d.kind == "message" or d.kind == "enum") and same_path(d, target.path)
    end)
end

