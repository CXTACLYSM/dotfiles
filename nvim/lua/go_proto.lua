-- protoc-gen-go names: user_id → UserId.
function M.go_name(name)
    return (name:gsub("^%l", string.upper):gsub("_(%l)", string.upper))
end

-- Every declaration of a .proto with the blocks around it:
-- { kind = rpc|service|message|enum|field, name, path (Outer.Inner),
--   service, row (0-based), col }.
function M.proto_declarations(lines)
    local stack, out = {}, {}
    local function enclosing(kind)
        for index = #stack, 1, -1 do
            if stack[index].kind == kind then
                return stack[index]
            end
        end
    end
    local function path(name)
        local names = {}
        for _, block in ipairs(stack) do
            if block.kind == "message" or block.kind == "enum" then
                table.insert(names, block.name)
            end
        end
        if name then
            table.insert(names, name)
        end
        return table.concat(names, ".")
    end
    for row, raw in ipairs(lines) do
        local line = raw:gsub("//.*$", ""):gsub('"[^"]*"', '""')
        local kind, name = line:match("^%s*(%a+)%s+([%w_]+)")
        local col = name and (line:find(name, 1, true) - 1)
        local declared = kind == "rpc" or kind == "service" or kind == "message" or kind == "enum" or kind == "oneof"
        if declared and kind ~= "oneof" then
            local service = enclosing("service")
            table.insert(out, {
                kind = kind,
                name = name,
                path = kind == "rpc" and name or path(name),
                service = service and service.name,
                row = row - 1,
                col = col,
            })
        elseif not declared then
            local field = line:match("^%s*[%w_.<>, ]-%s([%w_]+)%s*=%s*%d+")
            local message = enclosing("message")
            if field and message and stack[#stack].kind ~= "enum" then
                table.insert(out, {
                    kind = "field",
                    name = field,
                    path = path(),
                    row = row - 1,
                    col = line:find(field .. "%s*=") - 1,
                })
            end
        end
        local opens = select(2, line:gsub("{", ""))
        local closes = select(2, line:gsub("}", ""))
        for index = 1, opens do
            table.insert(stack, index == 1 and declared and { kind = kind, name = name } or { kind = "block" })
        end
        for _ = 1, closes do
            table.remove(stack)
        end
    end
    return out
end

-- What the cursor row of a .proto is about: the declaration on it, or the
-- block around it.
function M.proto_target(lines, row)
    local declarations = M.proto_declarations(lines)
    local around
    for _, declaration in ipairs(declarations) do
        if declaration.row == row then
            return declaration
        end
        if declaration.row < row and declaration.kind ~= "field" then
            around = declaration
        end
    end
    return around
end

