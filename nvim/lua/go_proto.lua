-- grp: between the .proto contracts and the Go code, both ways.
--
-- In a .proto file:
--   rpc X       the Go implementation of X (the handler); the generated
--               Unimplemented… and mocks are set aside; several open a
--               picker; none yet — the method of the generated interface
--   service S   the types that implement SServer
--   message M   the generated struct (Outer_Inner for a nested one); on a
--               field, that field of it
--   enum E      the generated type
-- In Go, on a name defined by generated code (a message, its field or
-- getter, a method of the client or server interface) or on a handler
-- method that implements a server interface: its place in the .proto.
--
-- Generated files name their source (`// source: order/v1/order.proto`);
-- the .proto is the file of the project that ends with that path. gopls
-- finds the implementations from the server interface and the interface
-- a handler satisfies; a .proto opened before any Go file starts gopls on
-- the generated one.

local M = {}

M.opts = { timeout_ms = 15000 }

local function notify(message, level)
    vim.notify(message, level or vim.log.levels.INFO, { title = "grp" })
end

local function file_lines(path)
    local bufnr = vim.fn.bufnr(path)
    if bufnr ~= -1 and vim.api.nvim_buf_is_loaded(bufnr) then
        return vim.api.nvim_buf_get_lines(bufnr, 0, -1, false)
    end
    local ok, lines = pcall(vim.fn.readfile, path)
    return ok and lines or nil
end

-- Generated by protoc for this file: *.pb.go, *_grpc.pb.go, *.pb.*.go …
local function generated(root, path)
    local rel = vim.fs.relpath(root, path)
    return rel ~= nil and rel:match("%.go$") ~= nil and require("categories").classify(rel) == "rpc"
end

-- Mocks, fakes and tests: implementations rarely wanted.
local function double(path)
    local lower = path:lower()
    return lower:match("_test%.go$") ~= nil or lower:match("/mocks?/") ~= nil
        or lower:match("/fakes?/") ~= nil or lower:match("mock[^/]*%.go$") ~= nil
end

local function lines_of(cmd, cwd)
    local result = vim.system(cmd, { cwd = cwd, text = true }):wait()
    return vim.split(result.stdout or "", "\n", { trimempty = true })
end

-- Go files generated from `proto` (relative to root): those whose
-- `// source:` path ends the proto path.
function M.generated_files(root, proto)
    local files = {}
    for _, line in ipairs(lines_of({
        "rg", "--no-ignore", "--no-heading", "--with-filename", "--no-line-number", "--max-count", "1",
        "--glob", "*.go", "--glob", "!**/node_modules/**", "-e", "^// source: ",
    }, root)) do
        local file, source = line:match("^(.-):// source: (%S+)")
        if file and (proto == source or proto:sub(-#source - 1) == "/" .. source) then
            table.insert(files, root .. "/" .. file)
        end
    end
    table.sort(files)
    return files
end

-- The .proto of the project for a `// source:` path; vendored copies last.
function M.proto_for(root, source)
    local found = {}
    for _, rel in ipairs(lines_of({ "rg", "--files", "--no-ignore", "--glob", "*.proto", "--glob", "!**/node_modules/**" }, root)) do
        if rel == source or rel:sub(-#source - 1) == "/" .. source then
            table.insert(found, rel)
        end
    end
    table.sort(found, function(a, b)
        local va, vb = a:find("vendor") ~= nil, b:find("vendor") ~= nil
        if va ~= vb then
            return vb
        end
        return #a < #b
    end)
    return found[1] and (root .. "/" .. found[1]) or nil
end

local function source_of(path)
    for index, line in ipairs(file_lines(path) or {}) do
        local source = line:match("^// source: (%S+)")
        if source then
            return source
        end
        if index > 40 then
            break
        end
    end
    return nil
end

