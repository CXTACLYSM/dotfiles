local function jump(path, row, col)
    vim.cmd("normal! m'")
    if vim.fs.normalize(vim.api.nvim_buf_get_name(0)) ~= vim.fs.normalize(path) then
        vim.cmd.edit(vim.fn.fnameescape(path))
    end
    pcall(vim.api.nvim_win_set_cursor, 0, { row + 1, col })
    vim.cmd("normal! zz")
end

local function pick(root, locations, title)
    local fzf = require("fzf-lua")
    local entries = {}
    for _, location in ipairs(locations) do
        local line = (file_lines(location.path) or {})[location.row + 1] or ""
        table.insert(entries, string.format("%s:%d:%d: %s",
            vim.fs.relpath(root, location.path) or location.path, location.row + 1, location.col + 1, vim.trim(line)))
    end
    fzf.fzf_exec(entries, {
        prompt = "Implementations> ",
        cwd = root,
        previewer = "builtin",
        actions = fzf.defaults.actions.files,
        fzf_opts = { ["--no-sort"] = true },
        winopts = { title = title },
    })
end

-- A gopls client: the running one, or one started on the Go file `path`
-- by loading it in a hidden buffer.
function M.with_gopls(path, callback)
    local client = vim.lsp.get_clients({ name = "gopls" })[1]
    if client then
        return callback(client)
    end
    local buf = vim.fn.bufadd(path)
    local attached = false
    vim.api.nvim_create_autocmd("LspAttach", {
        buffer = buf,
        once = true,
        callback = function(event)
            local started = vim.lsp.get_client_by_id(event.data.client_id)
            if started and started.name == "gopls" then
                attached = true
                callback(started)
            end
        end,
    })
    vim.fn.bufload(buf)
    vim.defer_fn(function()
        if not attached then
            notify("gopls did not start", vim.log.levels.WARN)
        end
    end, M.opts.timeout_ms)
end

local function locations(result, encoding)
    local out = {}
    for _, item in ipairs(result and (vim.islist(result) and result or { result }) or {}) do
        local uri = item.uri or item.targetUri
        local range = item.targetSelectionRange or item.range
        if uri and range then
            local path = vim.uri_to_fname(uri)
            local line = (file_lines(path) or {})[range.start.line + 1] or ""
            table.insert(out, {
                path = path,
                row = range.start.line,
                col = vim.str_byteindex(line, encoding, range.start.character, false),
            })
        end
    end
    return out
end

-- .proto → Go. `done(place)` for tests; nil `done` jumps.
function M.to_go(root, done)
    local path = vim.api.nvim_buf_get_name(0)
    local rel = vim.fs.relpath(root, path) or path
    local lines = vim.api.nvim_buf_get_lines(0, 0, -1, false)
    local target = M.proto_target(lines, vim.api.nvim_win_get_cursor(0)[1] - 1)
    if not target then
        notify("Nothing to find here: put the cursor on an rpc, service, message, enum or field")
        return
    end
    local files = M.generated_files(root, rel)
    local place = #files > 0 and M.go_place(files, target)
    if not place then
        notify(string.format("No generated Go for %s %s (regenerate the code?)", target.kind, target.name or target.path))
        return
    end
    if target.kind ~= "rpc" and target.kind ~= "service" then
        if done then
            done({ place })
        else
            jump(place.path, place.row, place.col)
        end
        return
    end

    M.with_gopls(place.path, function(client)
        local line = (file_lines(place.path) or {})[place.row + 1] or ""
        client:request("textDocument/implementation", {
            textDocument = { uri = vim.uri_from_fname(place.path) },
            position = { line = place.row, character = vim.str_utfindex(line, client.offset_encoding, place.col, false) },
        }, function(err, result)
            local real, doubles = {}, {}
            for _, location in ipairs(not err and locations(result, client.offset_encoding) or {}) do
                if not generated(root, location.path) then
                    table.insert(double(location.path) and doubles or real, location)
                end
            end
            if done then
                return done(real, doubles, place)
            end
            if #real == 1 then
                jump(real[1].path, real[1].row, real[1].col)
            elseif #real > 1 then
                pick(root, real, string.format(" %s: %d implementations ", target.name, #real))
            else
                jump(place.path, place.row, place.col)
                notify(string.format("%s has no implementation yet%s", target.name,
                    #doubles > 0 and string.format(" (%d in mocks/tests)", #doubles) or ""))
            end
        end)
    end)
end

-- A generated place → its .proto declaration.
local function from_generated(root, place, done)
    local source = source_of(place.path)
    local proto = source and M.proto_for(root, source)
    local target = M.go_target(file_lines(place.path) or {}, place.row, place.col)
    if not (proto and target) then
        return false
    end
    local found = M.proto_place(file_lines(proto) or {}, target)
    if not found then
        notify(string.format("%s is not in %s", target.name or target.path, vim.fs.relpath(root, proto) or proto))
        return true
    end
    if done then
        done({ path = proto, row = found.row, col = found.col })
    else
        jump(proto, found.row, found.col)
    end
    return true
end

-- Go → .proto. `done(place)` for tests; nil `done` jumps.
function M.to_proto(root, done)
    local bufnr = vim.api.nvim_get_current_buf()
    local cursor = vim.api.nvim_win_get_cursor(0)
    local here = { path = vim.api.nvim_buf_get_name(bufnr), row = cursor[1] - 1, col = cursor[2] }
    if generated(root, here.path) and from_generated(root, here, done) then
        return
    end
    local client = vim.lsp.get_clients({ bufnr = bufnr, name = "gopls" })[1]
    if not client then
        notify("No gopls in this buffer")
        return
    end
    local params = vim.lsp.util.make_position_params(0, client.offset_encoding)
    client:request("textDocument/definition", params, function(_, result)
        local definition = locations(result, client.offset_encoding)[1]
        if definition and generated(root, definition.path) and from_generated(root, definition, done) then
            return
        end
        -- A handler method: the server interface it satisfies.
        local at = definition or here
        local line = (file_lines(at.path) or {})[at.row + 1] or ""
        client:request("textDocument/implementation", {
            textDocument = { uri = vim.uri_from_fname(at.path) },
            position = { line = at.row, character = vim.str_utfindex(line, client.offset_encoding, at.col, false) },
        }, function(err, implemented)
            for _, location in ipairs(not err and locations(implemented, client.offset_encoding) or {}) do
                if generated(root, location.path) and from_generated(root, location, done) then
                    return
                end
            end
            notify("Not generated from a .proto, and implements no generated interface")
        end, bufnr)
    end, bufnr)
end

function M.jump(root)
    if vim.bo.filetype == "proto" then
        M.to_go(root)
    elseif vim.bo.filetype == "go" then
        M.to_proto(root)
    else
        notify("grp works in Go and .proto files")
    end
end

return M
